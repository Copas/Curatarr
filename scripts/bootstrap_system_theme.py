"""Write curatarr/static/bootstrap-system.css: Bootstrap's dark colours for
a page that follows the device's light or dark setting.

Bootstrap 5.3 switches to dark only under [data-bs-theme=dark], an attribute
the page sets when someone picked dark. A page with no choice saved has no
attribute and should follow the device: this copies every Bootstrap rule
written for [data-bs-theme=dark] into @media (prefers-color-scheme: dark),
for :root:not([data-bs-theme]). No script is involved, so it works before
any script runs, and without one.

Run after replacing static/bootstrap.min.css:
    .venv/bin/python scripts/bootstrap_system_theme.py
tests/test_page_security.py checks the file matches what this writes.
"""

from pathlib import Path

STATIC = Path(__file__).resolve().parents[1] / "curatarr" / "static"
DARK = "[data-bs-theme=dark]"
SYSTEM = ":root:not([data-bs-theme])"


def top_level_rules(css: str):
    """(prelude, body) of each top-level block, at-rules included whole."""
    depth, start, prelude_end = 0, 0, None
    for i, ch in enumerate(css):
        if ch == "{":
            if depth == 0:
                prelude_end = i
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                yield css[start:prelude_end].strip(), css[prelude_end + 1 : i]
                start = i + 1


def system_css(bootstrap: str) -> str:
    rules = []
    for prelude, body in top_level_rules(bootstrap):
        if prelude.startswith("@"):
            if DARK in body:
                raise ValueError(f"dark rule inside {prelude[:40]}: not handled")
            continue
        if DARK not in prelude:
            continue
        selectors = []
        for selector in prelude.split(","):
            selector = selector.strip()
            if selector == DARK:
                selectors.append(SYSTEM)
            elif selector.startswith(DARK + " "):
                selectors.append(SYSTEM + selector[len(DARK) :])
            # "[data-bs-theme=dark].carousel": a part marked dark on its
            # own, which a page following the device never has.
        if selectors:
            rules.append(f"{','.join(selectors)}{{{body}}}")
    return (
        "/* Generated by scripts/bootstrap_system_theme.py from bootstrap.min.css"
        " (Bootstrap 5.3.3, MIT): its dark colours for a page following the"
        " device's setting. Don't edit by hand. */\n"
        "@media (prefers-color-scheme: dark){" + "".join(rules) + "}\n"
    )


def main():
    bootstrap = (STATIC / "bootstrap.min.css").read_text(encoding="utf-8")
    (STATIC / "bootstrap-system.css").write_text(
        system_css(bootstrap), encoding="utf-8"
    )


if __name__ == "__main__":
    main()
